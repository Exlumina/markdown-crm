// Inactive cleanup (e.g. window blur/Escape) must not swallow the next record click.
const vm=require('node:vm'),fs=require('node:fs');
const sandbox=vm.createContext({performance:{now:()=>1000},cancelAnimationFrame:()=>{}});
vm.runInContext(fs.readFileSync(__dirname+'/static/app.js','utf8'),sandbox);
vm.runInContext('document={querySelectorAll:()=>[]}; stopDrag();',sandbox);
assert.equal(vm.runInContext('suppressClickUntil',sandbox),0);
vm.runInContext("drag={id:'a'}; stopDrag();",sandbox);
assert.equal(vm.runInContext('suppressClickUntil',sandbox),1250);
// Repeated cleanup must not extend the suppression window.
sandbox.performance.now=()=>1100;
vm.runInContext('stopDrag();',sandbox);
assert.equal(vm.runInContext('suppressClickUntil',sandbox),1250);
console.log('Click regression passed: inactive cleanup preserves clicks; real drags suppress only their trailing click.');
